// Extracts the handful of brand marks TalkGraph uses from simple-icons (CC0)
// into a small generated module, so the client bundle never ships all ~3k icons.
// Run: node scripts/gen-brand-icons.mjs
import * as icons from "simple-icons";
import { writeFileSync } from "node:fs";

const WANTED = {
  postgres: "siPostgresql",
  mysql: "siMysql",
  mongodb: "siMongodb",
  redis: "siRedis",
  kafka: "siApachekafka",
  rabbitmq: "siRabbitmq",
  elasticsearch: "siElasticsearch",
  cassandra: "siApachecassandra",
  grafana: "siGrafana",
  prometheus: "siPrometheus",
  opentelemetry: "siOpentelemetry",
  stripe: "siStripe",
  auth0: "siAuth0",
  vault: "siVault",
  nginx: "siNginx",
  cloudflare: "siCloudflare",
  graphql: "siGraphql",
  snowflake: "siSnowflake",
  pubsub: "siGooglepubsub",
  nats: "siNatsdotio",
  anthropic: "siAnthropic",
  qdrant: "siQdrant",
  socketio: "siSocketdotio",
  kong: "siKong",
  pagerduty: "siPagerduty",
  sentry: "siSentry",
  datadog: "siDatadog",
  minio: "siMinio",
};

const out = {};
for (const [key, name] of Object.entries(WANTED)) {
  const icon = icons[name];
  if (!icon) throw new Error(`simple-icons is missing ${name}`);
  out[key] = { title: icon.title, path: icon.path };
}

const body = `// GENERATED by scripts/gen-brand-icons.mjs from simple-icons (CC0-1.0). Do not edit.
export const BRAND_ICONS = ${JSON.stringify(out, null, 2)} as const;

export type BrandIconKey = keyof typeof BRAND_ICONS;
`;
writeFileSync(new URL("../src/domain/brand-icons.generated.ts", import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} brand icons`);
